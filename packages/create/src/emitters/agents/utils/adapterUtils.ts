import { RUN_PREFIX } from '@config/constants';
import {
  type Answers,
  type Artifact,
  type Workspace,
  type WorkspaceProject,
} from '@config/types';

import { projectDirectoryOf } from '@utils/answerUtils';

import { emitted, merged } from '../../utils/artifactUtils';

import { labelOf, ruleGroups } from './ruleGroupUtils';

export const emitAgentAdapter = (answers: Answers): string => {
  const run = RUN_PREFIX[answers.packageManager];

  return `# LintelJS project

- Before a change, follow \`plugins/linteljs/skills/linteljs/SKILL.md\`: it names the rule file for that kind of change.
- Read \`package.json\` for exact scripts and dependency versions.
- Run \`${run} check\` before declaring implementation work complete.
- Run it alone or redirected out of the work tree (\`${run} check > /tmp/check.log 2>&1\`), never piped or chained.
  Leading \`NAME=value\` assignments are fine.
- In Claude Code a commit waits until that run has passed on the work tree it would commit.
- Never edit a file whose first line marks it generated.
- Run \`${run} lint:fix\`, not lint without fixes.
- Comments are minimal: a short why, or none. Never restate the code; no comments in tests.
- Never use \`git stash\`, \`git reset\`, \`--no-verify\`, \`--amend\`, \`git add -A\`, or \`git add .\`.
- Commit messages carry no \`Co-Authored-By\` or tool-attribution trailers.
`;
};

const BLOCK = /<!-- linteljs:projects -->\n[\s\S]*?<!-- \/linteljs:projects -->\n/u;

const kindOf = (answers: Answers): string => {
  return labelOf(answers) === 'package' ? 'package' : 'app';
};

const projectsBlock = (workspace: Workspace): string => {
  const lines = workspace.projects
    .map(({ name, answers }) => {
      return `- \`${projectDirectoryOf(answers, name)}\` - ${kindOf(answers)}, ${answers.target}`;
    });

  return `<!-- linteljs:projects -->
## Projects

Each has its own \`CLAUDE.md\` or \`AGENTS.md\` naming its rule files.

${lines.join('\n')}
<!-- /linteljs:projects -->
`;
};

// A project's own instructions outrank a re-run; in a monorepo only the projects block is sync's.
export const adapterArtifact = (target: string, workspace: Workspace, header = ''): Artifact => {
  const [{ answers }] = workspace.projects;
  const adapter = `${header}${emitAgentAdapter(answers)}`;

  if (answers.layout !== 'monorepo') {
    const preserved: Artifact = {
      ...emitted('standard', target, adapter),
      preserve: true,
    };

    return preserved;
  }

  const block = projectsBlock(workspace);

  return merged('standard', target, (current) => {
    if (current === null) {
      return `${adapter}\n${block}`;
    }

    // A function, so a `$` in a project name is never read as a replacement pattern.
    return BLOCK.test(current)
      ? current
          .replace(BLOCK, () => {
            return block;
          })
      : `${current}\n${block}`;
  });
};

export const projectFacts = (workspace: Workspace, { name, answers }: WorkspaceProject): string => {
  const directory = projectDirectoryOf(answers, name);
  const run = RUN_PREFIX[answers.packageManager];
  const rules = ruleGroups(workspace)
    .filter(({ directories }) => {
      return directories.includes(directory);
    })
    .map((group) => {
      return `  - \`${group.name}\``;
    });

  return `<!-- Generated by linteljs sync. Do not edit. -->

# ${name}

- Kind: ${kindOf(answers)} on ${answers.target}, in \`${directory}\`.
- \`${run} check\` run here checks this project alone; run at the repository root, every project.
- Its rule files, in \`plugins/linteljs/skills/linteljs/references/\` at the repository root:
${rules.join('\n')}
`;
};

// The root adapter, and in a monorepo each project's facts beside it.
export const instructionArtifacts = (workspace: Workspace, file: string): Artifact[] => {
  const [{ answers }] = workspace.projects;
  const projects = answers.layout === 'monorepo'
    ? workspace.projects
        .map((project) => {
          const directory = projectDirectoryOf(project.answers, project.name);
          const facts = projectFacts(workspace, project);

          return emitted('standard', `${directory}/${file}`, facts);
        })
    : [];

  const artifacts = [adapterArtifact(file, workspace), ...projects];

  return artifacts;
};
