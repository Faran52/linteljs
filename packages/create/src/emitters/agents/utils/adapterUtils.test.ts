import { targets } from '@mocks/agentRules';
import { hostedAnswersFor, soloOf } from '@mocks/answersFor';
import {
  describe,
  expect,
  it,
} from 'vitest';

import { type Artifact, type Workspace } from '@config/types';

import { DEFAULT_ANSWERS } from '@answers';

import { workspaceOf } from '../../utils/layoutUtils';

import {
  adapterArtifact,
  emitAgentAdapter,
  instructionArtifacts,
  projectFacts,
} from './adapterUtils';

describe('emitAgentAdapter', () => {
  it('points at the skill, the gate, the dependency ask, the comment rule and the git bans, and nothing else', () => {
    const agentAdapter = emitAgentAdapter(DEFAULT_ANSWERS);

    expect(agentAdapter).toBe(`# LintelJS project

- Before a change, follow \`plugins/linteljs/skills/linteljs/SKILL.md\`: it names the rule file for that kind of change.
- Read \`package.json\` for exact scripts and dependency versions.
- Run \`pnpm check\` before declaring implementation work complete.
- Run it alone or redirected out of the work tree (\`pnpm check > /tmp/check.log 2>&1\`), never piped or chained.
  Leading \`NAME=value\` assignments are fine.
- In Claude Code a commit before that run has passed on the work tree it would commit asks the user first.
- Never edit a file whose first line marks it generated.
- Run \`pnpm lint:fix\`, not lint without fixes.
- Comments are minimal: a short why, or none. Never restate the code; no comments in tests.
- Never use \`git stash\`, \`git reset\`, \`--no-verify\`, \`--amend\`, \`git add -A\`, or \`git add .\`.
- Commit messages carry no \`Co-Authored-By\` or tool-attribution trailers.
`);
  });

  it('spells every script the way the chosen manager runs it', () => {
    const adapter = emitAgentAdapter({
      ...DEFAULT_ANSWERS,
      packageManager: 'npm',
    });

    expect(adapter).toContain('`npm run check`');
    expect(adapter).toContain('`npm run lint:fix`');
  });
});

const monorepoOf = (): Workspace => {
  const workspace = workspaceOf('acme', [
    { name: 'web', answers: hostedAnswersFor({ layout: 'monorepo', target: 'react' }) },
    { name: 'shared', answers: hostedAnswersFor({ layout: 'monorepo', target: 'typescript' }) },
  ]);

  return workspace;
};

const mergeOf = (artifact: Artifact): ((current: string | null) => string) => {
  if (!('merge' in artifact.content)) {
    throw new Error(`no merge for ${artifact.target}`);
  }

  return artifact.content.merge;
};

const BLOCK = `<!-- linteljs:projects -->
## Projects

Each has its own \`CLAUDE.md\` or \`AGENTS.md\` naming its rule files.

- \`apps/web\` - app, react
- \`packages/shared\` - package, typescript
<!-- /linteljs:projects -->
`;

describe('adapterArtifact', () => {
  it('writes the adapter to the named file and leaves a project copy of it alone', () => {
    const artifact = adapterArtifact('AGENTS.md', soloOf(DEFAULT_ANSWERS), 'head\n');

    expect(artifact.stage).toBe('standard');
    expect(artifact.target).toBe('AGENTS.md');
    expect(artifact.preserve).toBe(true);
    expect(artifact.content).toHaveProperty('text', `head\n${emitAgentAdapter(DEFAULT_ANSWERS)}`);
  });

  it('writes the projects block below a new monorepo adapter', () => {
    const artifact = adapterArtifact('CLAUDE.md', monorepoOf(), 'head\n');
    const merge = mergeOf(artifact);
    const written = merge(null);

    expect(artifact.preserve).toBeUndefined();
    expect(written).toBe(`head\n${emitAgentAdapter(DEFAULT_ANSWERS)}\n${BLOCK}`);
  });

  it('replaces only the block in a kept adapter, and appends it where it is missing', () => {
    const artifact = adapterArtifact('CLAUDE.md', monorepoOf());
    const merge = mergeOf(artifact);
    const stale = 'mine\n<!-- linteljs:projects -->\n- `apps/$&` - app\n<!-- /linteljs:projects -->\nmore\n';
    const replaced = merge(stale);
    const appended = merge('mine\n');

    expect(replaced).toBe(`mine\n${BLOCK}more\n`);
    expect(appended).toBe(`mine\n\n${BLOCK}`);
  });
});

describe('projectFacts', () => {
  it('marks itself generated and names the project, its check and its rule files', () => {
    const shared = { name: 'shared', answers: hostedAnswersFor({ layout: 'monorepo', target: 'typescript' }) };
    const workspace = workspaceOf('acme', [shared]);
    const facts = projectFacts(workspace, shared);

    expect(facts).toBe(`<!-- Generated by linteljs sync. Do not edit. -->

# shared

- Kind: package on typescript, in \`packages/shared\`.
- \`pnpm check\` run here checks this project alone; run at the repository root, every project.
- Its rule files, in \`plugins/linteljs/skills/linteljs/references/\` at the repository root:
  - \`type-standards.md\`
  - \`repo-structure.package.md\`
  - \`testing.package.md\`
`);
  });
});

describe('instructionArtifacts', () => {
  it('writes the adapter alone in a single layout', () => {
    const artifacts = instructionArtifacts(soloOf(DEFAULT_ANSWERS), 'AGENTS.md');
    const written = targets(artifacts);

    expect(written).toEqual(['AGENTS.md']);
  });

  it('writes each project\'s facts in its own directory in a monorepo', () => {
    const workspace = monorepoOf();
    const artifacts = instructionArtifacts(workspace, 'AGENTS.md');
    const written = targets(artifacts);

    expect(written).toEqual([
      'AGENTS.md',
      'apps/web/AGENTS.md',
      'packages/shared/AGENTS.md',
    ]);

    expect(artifacts[1]?.content).toHaveProperty('text', projectFacts(workspace, workspace.projects[0]));
  });
});

it('runs the gate without `run` under yarn', () => {
  const berry = emitAgentAdapter({
    ...DEFAULT_ANSWERS,
    packageManager: 'yarn',
  });

  expect(berry).toContain('`yarn check`');
});
