import { type Artifact, type Emitter } from '@config/types';

import { unscopedName } from '@utils/nameUtils';

import { targetFor } from '@targets';

import { emitted } from '../../utils/artifactUtils';

import {
  EXTENSION_ICON,
  FAVICON,
  type Icon,
} from './constants';

// `lang` set: an empty one tells a screen reader the language is unknown. Laid out as the html layer formats it.
export const emitHtmlEntry = (name: string, entry: string, icon?: Icon): string => {
  const page = [
    '<!doctype html>',
    '<html lang="en">',
    '    <head>',
    '        <meta charset="UTF-8">',
    '        <meta name="viewport" content="width=device-width, initial-scale=1.0">',
    `        <title>${name}</title>`,
    `        <meta name="description" content="${name}, generated by linteljs">`,
    ...icon === undefined
      ? []
      : [
          '        <link',
          '            rel="icon"',
          `            type="${icon.type}"`,
          `            href="${icon.href}"`,
          '        >',
        ],
    '    </head>',
    '    <body>',
    '        <div id="root"></div>',
    `        <script type="module" src="/${entry}"></script>`,
    '    </body>',
    '</html>',
    '',
  ].join('\n');

  return page;
};

export const htmlEntryEmitter: Emitter = (answers, _project, name): Artifact[] => {
  const {
    htmlEntry,
    publicDirectory,
    hostsBrowser,
  } = targetFor(answers);
  // Without one, the popup page in a tab, or served by `vite`, asks for a `/favicon.ico` that 404s.
  const extensionIcon = hostsBrowser === true ? EXTENSION_ICON : undefined;
  const icon = publicDirectory === undefined ? extensionIcon : FAVICON;

  if (htmlEntry === undefined) {
    return [];
  }

  const page = emitHtmlEntry(unscopedName(name), htmlEntry, icon);
  const artifacts = [emitted('standard', 'index.html', page)];

  return artifacts;
};
